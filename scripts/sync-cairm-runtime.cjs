// Generate the offline audit engine from the actual Cairm production functions.
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const sourcePath = path.resolve(__dirname, '../../Cairm/extensions/cairm/content.js');
const target = path.resolve(__dirname, '../src/renderer/cairm-runtime.js');
const names = ['normalizeText', 'normalizeComparableText', 'normalizeLocalIdentityKey', 'findLocalIdentityMatches', 'pushLocalRuleAlias',
  'resolveProductIdsFromActiveBundleComposition', 'normalizeActiveBundleProductIds', 'buildLocalServiceIndex',
  'installLocalServiceRulesFromCairmDb', 'resolveLocalIndexEntry', 'resolveExactLocalIndexEntry', 'resolveLocalCountry',
  'resolveLocalProductOrBundle', 'normalizeServiceStatus', 'formatWarrantyDuration', 'formatServicePrice', 'getLocationLabel',
  'combineServiceStatuses', 'combineServiceLevels', 'isRestrictiveCountryStatus', 'getCountryTemporaryCommentOverride',
  'isFranceCountryInfo', 'normalizeProductSkuValues', 'resolveProductSkuValues', 'buildLocalProductServiceDetail',
  'resolveLocalDocumentServiceData', 'getSignalValueLabel', 'formatExchangeStatus', 'formatServiceExchangeLabel'];
function generate() {
  const source = fs.readFileSync(sourcePath, 'utf8');
  const functions = names.map(name => {
    const start = source.indexOf(`  function ${name}(`);
    const end = source.indexOf('\n  }', start);
    if (start < 0 || end < 0) throw new Error(`Missing Cairm function: ${name}`);
    return source.slice(start, end + 4);
  }).join('\n\n');
  const hash = crypto.createHash('sha256').update(functions).digest('hex');
  const version = JSON.parse(fs.readFileSync(path.join(path.dirname(sourcePath), 'manifest.json'))).version;
  return `// Generated by scripts/sync-cairm-runtime.cjs. Do not edit.\n(function(root) {\n  function create(db) {\n    let localServiceRules = {}, localServiceRulesState = {};\n    const COUNTRY_TEMPORARY_COMMENT_SECTIONS = new Set(['spare_parts', 'rma', 'paid_rma', 'exchange']);\n    // Notes do not determine availability; no DOM is required for the audit.\n    const getHeaderSignalsNote = value => String(value ?? '').trim() === '0' ? '' : String(value ?? '').trim();\n    const translateCairnContent = (key, fallback) => fallback;\n${functions}\n    installLocalServiceRulesFromCairmDb(db);\n    return { resolve: resolveLocalDocumentServiceData, identityKey: normalizeLocalIdentityKey, resolveCountry: resolveLocalCountry, resolveProduct: resolveLocalProductOrBundle, rules: localServiceRules, formatWarrantyDuration, getSignalValueLabel, formatServiceExchangeLabel };\n  }\n  const api = { create, version: ${JSON.stringify(version)}, sourceHash: ${JSON.stringify(hash)} };\n  if (typeof module !== 'undefined' && module.exports) module.exports = api;\n  else root.CairmAuditRuntime = api;\n})(globalThis);\n`;
}
if (require.main === module) {
  const output = generate();
  if (process.argv.includes('--check')) {
    if (fs.readFileSync(target, 'utf8') !== output) throw new Error('Cairm audit engine is stale. Run npm run sync:cairm.');
  } else fs.writeFileSync(target, output);
}
module.exports = { generate, target };
