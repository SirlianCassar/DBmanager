const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const { chromium } = require('playwright');
(async () => {
  const browser = await chromium.launch({ channel: 'msedge', headless: true });
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 1100 } });
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    const db = { ids: { countries: { C1: { name: 'France' } }, products: { P1: { name: 'Test product' } }, bundles: {}, locations: {} }, countries: { C1: { ga_zone: 'europe', rma: { status: 'temp' }, spare_parts: { status: 'yes' }, note: 'Country ordinary' } }, products: { P1: { note: 'Global ordinary', zones: { europe: { rma: { status: 'yes', paid: { price: 25 } }, spare_parts: { status: 'temp' }, exchange: { status: 'us' }, note: 'Region ordinary' } } } } };
    await page.addInitScript(db => { window.cairmDesktop = { loadDefaultDatabase: async () => JSON.stringify(db) }; }, db);
    const html = fs.readFileSync(path.join(__dirname, '../src/renderer/index.html'), 'utf8').replace('      loadDb();', '      window.testState = state; window.testExport = buildExportDb;\n      loadDb();');
    await page.route('http://cairmdb.test/**', route => {
      const filename = route.request().url().endsWith('.js') ? 'db-maintenance.js' : route.request().url().endsWith('.css') ? 'rework.css' : '';
      return route.fulfill({ contentType: filename.endsWith('.js') ? 'text/javascript' : filename ? 'text/css' : 'text/html', body: filename ? fs.readFileSync(path.join(__dirname, '../src/renderer', filename), 'utf8') : html });
    });
    await page.goto('http://cairmdb.test/');
    await page.click('#tab-wws');
    assert.equal(await page.locator('#countryEditor [data-service]').count(), 4);
    assert.equal(await page.locator('#countryEditor [data-service-legacy]').inputValue(), 'temp');
    await page.locator('#countryEditor [data-important-enabled] + .slider').click();
    await page.locator('#countryEditor [data-important-section="rma"]').check();
    await page.locator('#countryEditor [data-important-comment]').fill('Country important');
    await page.click('#tab-ga');
    assert.equal(await page.locator('#productEditor [data-service]').count(), 4);
    assert.equal(await page.locator('#productEditor [data-service="paid"] [data-service-toggle]').isChecked(), true, 'Legacy price implies Yes');
    assert.equal(await page.locator('#productEditor [data-service="spare_parts"] [data-service-legacy]').inputValue(), 'temp');
    assert.equal(await page.locator('[data-product-field="exchange.destination"]').inputValue(), 'us');
    await page.locator('[data-product-field="exchange.destination"]').selectOption('retailer');
    for (const scope of ['region', 'global']) {
      const block = page.locator(`[data-important-scope="${scope}"]`);
      await block.locator('[data-important-enabled] + .slider').click();
      await block.locator('[data-important-section="exchange"]').check();
      await block.locator('[data-important-comment]').fill(`${scope} important`);
    }
    const saved = await page.evaluate(() => JSON.parse(JSON.stringify(testState.db)));
    assert.equal(saved.countries.C1.rma.status, 'temp');
    assert.equal(saved.countries.C1.note, 'Country ordinary');
    assert.equal(saved.products.P1.zones.europe.spare_parts.status, 'temp');
    assert.equal(saved.products.P1.zones.europe.exchange.status, 'yes');
    assert.equal(saved.products.P1.zones.europe.exchange.destination, 'retailer');
    assert.equal(saved.products.P1.note, 'Global ordinary');
    assert.equal(saved.products.P1.zones.europe.note, 'Region ordinary');
    assert.equal(saved.products.P1.temporary_comment.comment, 'global important');
    assert.equal(saved.products.P1.zones.europe.temporary_comment.comment, 'region important');
    await page.locator('[data-important-scope="region"] [data-important-enabled] + .slider').click();
    assert.equal(await page.evaluate(() => testState.db.products.P1.zones.europe.temporary_comment.comment), 'region important');
    await page.locator('[data-service="spare_parts"] [data-service-legacy]').selectOption('no');
    await page.locator('#productEditor [data-service-legacy]').waitFor({ state: 'detached' });
    assert.equal(await page.locator('#productEditor [data-service-legacy]').count(), 0, 'Temp cannot be reintroduced after choosing No');
    assert.equal(await page.evaluate(() => testState.db.products.P1.zones.europe.spare_parts.status), 'no');
    await page.click('#tab-wws');
    assert.equal(await page.locator('#newCountry').textContent(), '');
    const beforeCountries = await page.evaluate(() => Object.keys(testState.db.ids.countries).length);
    await page.click('#newCountry');
    await page.locator('#countryName').fill('France');
    await page.click('#saveCountry');
    assert.equal(await page.locator('#countryNameError').isVisible(), true, 'Duplicate country is rejected');
    await page.locator('#countryName').fill('Test country created');
    await page.click('#saveCountry');
    assert.equal(await page.evaluate(() => Object.keys(testState.db.ids.countries).length), beforeCountries + 1);
    await page.waitForFunction(() => Object.values(JSON.parse(localStorage.getItem('cairmdb-manager-draft'))?.ids?.countries || {}).some(c => c.name === 'Test country created'));
    await page.reload();
    await page.click('#tab-wws');
    assert.equal(await page.evaluate(() => Object.values(testState.db.ids.countries).some(c => c.name === 'Test country created')), true);
    await page.click('#newCountry');
    await page.locator('#countryName').fill('Cancelled country');
    await page.click('#cancelCountry');
    assert.equal(await page.evaluate(() => Object.keys(testState.db.ids.countries).length), beforeCountries + 1);
    await page.setViewportSize({ width: 980, height: 800 });
    assert.equal(await page.locator('#newCountry').evaluate(button => { const r = button.getBoundingClientRect(); return r.width > 0 && r.right <= innerWidth && button.contains(document.elementFromPoint(r.x + r.width / 2, r.y + r.height / 2)); }), true);
    await page.setViewportSize({ width: 1440, height: 1100 });
    await page.click('#tab-wws');
    await page.click('#newCountry');
    await page.locator('#countryName').fill('Manager new country');
    await page.click('#saveCountry');
    const countryId = await page.evaluate(() => testState.selectedCountryId);
    await page.click('#tab-ga');
    await page.click('#newProduct');
    await page.locator('#productName').fill('Manager new product');
    await page.click('#saveProduct');
    const productId = await page.evaluate(() => testState.selectedProductId);
    await page.click('#tab-sku');
    await page.locator(`[data-sku-product="${productId}"]`).click();
    await page.locator('#globalSku').fill('SKU-A\nSKU-B');
    await page.click('#tab-bundles');
    await page.click('#newBundle');
    await page.locator('#bundleName').fill('CRM new bundle');
    await page.locator('#bundleProductSearch').fill('Manager new product');
    await page.locator(`[data-add-product="${productId}"] button`).click();
    await page.click('#saveBundle');
    await page.locator('#bundleName').fill('CRM new bundle renamed');
    await page.click('#saveBundle');
    const exported = JSON.parse(JSON.stringify(await page.evaluate(() => testExport())));
    const { loadWwsxgaRuntime } = await import('../../Cairm/tools/lib/wwsxga-runtime.mjs');
    const runtime = loadWwsxgaRuntime(exported);
    assert.equal(runtime.resolveLocalCountry('Manager new country').id, countryId);
    assert.equal(runtime.resolveLocalProductOrBundle('Manager new product').id, productId);
    assert.equal(runtime.resolveLocalProductOrBundle('CRM new bundle renamed').productIds[0], productId);
    assert.deepEqual(Array.from(runtime.resolveProductSkuValues(exported.products[productId], { id: countryId, rule: {} }).values), ['SKU-A', 'SKU-B']);
    const skuRecord = { skus: { global: 'G1\nG2', regions: { europe: 'R1\nR2' }, countries: { [countryId]: 'C1\nC2' } } };
    assert.deepEqual(Array.from(runtime.resolveProductSkuValues(skuRecord, { id: countryId, rule: { ga_zone: 'europe' } }).values), ['C1', 'C2']);
    assert.deepEqual(Array.from(runtime.resolveProductSkuValues(skuRecord, { id: 'other', rule: { ga_zone: 'europe' } }).values), ['R1', 'R2']);
    await page.click('#tab-home');
    const crmIndex = { format: 'cairm-crm-index', formatVersion: 1, complete: true, countries: [{ name: 'Imported country' }], products: [{ name: 'Imported product' }, { name: 'Imported bundle', type: 'bundle' }] };
    await page.locator('#importCrmIndexFile').setInputFiles({ name: 'crm-index.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(crmIndex)) });
    const afterImport = await page.evaluate(() => testExport());
    const importedRuntime = loadWwsxgaRuntime(afterImport);
    const importedCountry = importedRuntime.resolveLocalCountry('Imported country');
    assert.equal(importedCountry.dataMissing, true);
    await page.click('#tab-wws');
    await page.locator(`[data-country="${importedCountry.id}"]`).click();
    assert.equal(await page.locator('#initializeCountryRules').count(), 1);
    assert.equal(await page.evaluate(id => testState.db.countries[id], importedCountry.id), undefined);
    await page.click('#tab-cleanup');
    await page.click('#cancelCleanup');
    assert.equal(await page.evaluate(() => Object.values(testState.db.ids.countries).some(row => row.name === 'Imported country')), false);
    const importedProduct = importedRuntime.resolveLocalProductOrBundle('Imported product');
    assert.equal(afterImport.products[importedProduct.id], undefined);
    assert.equal(importedRuntime.resolveLocalProductOrBundle('Imported bundle').type, 'bundle');
    await page.evaluate(() => { testState.db.ids.locations = { L999: { name: 'Unused test centre' } }; });
    await page.click('#scanDb');
    assert.match(await page.locator('#cleanupReport').textContent(), /Unused test centre/);
    await page.click('#sanitizeDb');
    assert.equal(await page.evaluate(() => testState.db.ids.locations.L999), undefined);
    await page.click('#cancelCleanup');
    assert.equal(await page.evaluate(() => testState.db.ids.locations.L999.name), 'Unused test centre');
    assert.deepEqual(errors, []);
    console.log('Editor browser OK: service editing; new country, product, bundle and Cleanup scan, sanitize and annulation.');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
