const assert = require('node:assert/strict');
const fs = require('node:fs');
const { importIndex, sanitize } = require('../src/renderer/db-maintenance.js');
const db = { ids: { countries: { C001: { name: 'United States' } }, products: { P001: { name: 'FK1' }, P002: { name: 'Duplicate' }, P003: { name: 'Duplicate' } }, bundles: { B001: { name: 'Bundle', products: ['P001'] } }, locations: {} }, countries: {}, products: {} };
const catalog = { format: 'cairm-crm-index', formatVersion: 1, complete: true, countries: [{ name: 'États-Unis' }, { name: 'New country' }], products: [{ name: 'FK1' }, { name: 'FK2', crmId: 'same-as-fk1' }, { name: 'FK2' }, { name: 'Bundle' }, { name: 'Duplicate' }, { name: 'New bundle', type: 'bundle' }] };
const before = JSON.stringify(db);
const { db: imported, report } = importIndex(db, catalog);
assert.equal(JSON.stringify(db), before, 'Input not mutated');
assert.equal(report.added.length, 3);
assert.equal(report.issues.length, 1);
assert.equal(Object.keys(imported.countries).length, 0);
assert.equal(Object.keys(imported.products).length, 0);
assert.deepEqual(imported.ids.bundles.B002.products, []);
assert.equal(importIndex(imported, catalog).report.added.length, 0, 'Repeated imports are idempotent');
assert.equal(importIndex(db, { ...catalog, complete: false }).report.partial, true);
assert.throws(() => importIndex(db, { countries: [] }), /Expected/);
assert.throws(() => importIndex(db, { ...catalog, products: [{ name: 42 }] }), /Invalid/);
const fixture = structuredClone(db);
fixture.ids.products.P001.aliases = ['FK1', 'FK1', '', '11111111-2222-3333-4444-555555555555'];
fixture.ids.products.P001.crm_id = 'ignored';
fixture.ids.products.P001._source = { file: 'old' };
fixture.ids.locations = { L1: { name: 'Used' }, L2: { name: 'Unused' }, L3: { name: 'CHECK HERE' }, L4: { name: 'Future referenced' } };
fixture.products.P001 = { zones: { europe: { rma: { status: 'temp', location: 'L1', paid: { status: 'no', price: 25 } }, exchange: { status: 'both' }, spare_parts: { status: 'yes', location: 'L3' }, note: 'Keep note' } } };
fixture.future = { destination: 'L4' };
const clean = sanitize(fixture);
assert.equal(clean.db.products.P001.zones.europe.rma.status, 'temp');
assert.equal(clean.db.products.P001.zones.europe.exchange.status, 'retailer');
assert.equal(clean.db.products.P001.zones.europe.spare_parts.location, undefined);
assert.deepEqual(Object.keys(clean.db.ids.locations), ['L1', 'L4']);
assert.equal(clean.db.products.P001.zones.europe.rma.paid.price, 25, 'Inactive details are not assumed obsolete');
assert.equal(clean.db.products.P001.zones.europe.note, 'Keep note');
assert.deepEqual(clean.db.ids.products.P001.aliases, ['FK1']);
assert.equal(fixture.ids.locations.L2.name, 'Unused');
assert(clean.report.issues.some(row => row.reason.includes('temporary')));
assert(clean.report.issues.some(row => row.reason.includes('Ambiguous')));
assert.equal(sanitize(clean.db).report.changes.length, 0, 'Sanitize is idempotent');
// Incomplete records get No on their yes/no availabilities; absent ones stay absent.
const gaps = structuredClone(db);
gaps.ids.countries.C002 = { name: 'Skeleton' };
gaps.ids.countries.C003 = { name: 'Untouched' };
gaps.ids.products.P004 = { name: 'No rules' };
gaps.ids.products.P005 = { name: 'Odd status' };
gaps.countries.C001 = { ga_zone: 'europe', rma: { status: null, warranty_duration: 3 }, spare_parts: {}, paid_rma: { status: null }, exchange: {}, note: '' };
gaps.countries.C002 = { ga_zone: '', rma: { status: null, warranty_duration: null }, spare_parts: { status: null }, exchange: { status: null }, note: '' };
gaps.products.P001 = { zones: { europe: { rma: { status: 'yes' }, spare_parts: {}, note: 'Keep' } } };
gaps.products.P004 = { skus: ['SKU-1'] };
gaps.products.P005 = { zones: { europe: { rma: { status: 'maybe' }, spare_parts: { status: 'no' }, exchange: { status: 'us' } } } };
const filled = sanitize(gaps);
assert.equal(filled.db.countries.C001.rma.status, 'no', 'Missing availability of a started record becomes No');
assert.equal(filled.db.countries.C001.spare_parts.status, 'no');
assert.equal(filled.db.countries.C001.rma.warranty_duration, 3, 'Existing values are untouched');
assert.equal(filled.db.countries.C001.paid_rma.status, null, 'Only availabilities blocking completeness are filled');
assert.equal(filled.db.countries.C001.ga_zone, 'europe');
assert.deepEqual(filled.db.countries.C002, gaps.countries.C002, 'A record empty throughout counts as absent data');
assert.equal(filled.db.products.P001.zones.europe.rma.status, 'yes');
assert.equal(filled.db.products.P001.zones.europe.spare_parts.status, 'no');
assert.equal(filled.db.products.P001.zones.europe.exchange.status, 'no');
assert.equal(filled.db.products.P001.zones.europe.note, 'Keep');
assert.equal(filled.db.products.P001.zones.australia.rma.status, 'no', 'A region missing from a started product becomes No');
assert.equal(filled.db.products.P001.zones.rest_of_world.exchange.status, 'no');
assert.deepEqual(filled.db.products.P004, { skus: ['SKU-1'] }, 'A product without any region keeps no invented rule');
assert.equal(filled.db.products.P005.zones.europe.rma.status, 'maybe', 'An unrecognised value is reported, not overwritten');
assert(filled.report.issues.some(row => row.reason.includes('Unknown availability')));
assert.equal(filled.report.changes.filter(row => row.path.startsWith('countries.C002')).length, 0);
assert.equal(sanitize(filled.db).report.changes.length, 0, 'Completion is idempotent');
const real = JSON.parse(fs.readFileSync(require.resolve('../cairm-full-database.json'), 'utf8'));
const actual = sanitize(real);
assert.deepEqual(Object.keys(actual.db.ids.products), Object.keys(real.ids.products));
assert.deepEqual(Object.keys(actual.db.ids.countries), Object.keys(real.ids.countries));
assert.deepEqual(actual.db.activeBundles, real.activeBundles);
assert.equal(sanitize(actual.db).report.changes.length, 0);
console.log(`Maintenance OK: additive exact-name import, no invented business data, duplicates, ambiguity, partial/invalid input, incomplete records completed with No while absent data stays absent, safe cleanup and idempotence. Current DB: ${actual.report.changes.length} changes, ${actual.report.issues.length} retained issues.`);
